std::string html_escape(const std::string& s) {
    std::string r;
    for (char c : s) {
        switch (c) {
        case '&': r += "&amp;"; break;
        case '<': r += "&lt;"; break;
        case '>': r += "&gt;"; break;
        case '"': r += "&quot;"; break;
        default: r += c;
        }
    }
    return r;
}

void replace_all(std::string& t, const std::string& key, const std::string& with) {
    for (std::size_t at = t.find(key); at != std::string::npos; at = t.find(key, at + with.size()))
        t.replace(at, key.size(), with);
}

